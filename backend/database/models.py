from sqlalchemy import Column, Integer, String, DateTime, JSON, Text, ForeignKey
from sqlalchemy.orm import relationship
from pgvector.sqlalchemy import Vector
from datetime import datetime
from .connection import Base

class User(Base):
    __tablename__ = "users"

    id = Column(Integer, primary_key=True, index=True)
    name = Column(String, nullable=False)
    email = Column(String, unique=True, index=True, nullable=False)
    hashed_password = Column(String, nullable=False)
    created_at = Column(DateTime, default=datetime.utcnow)


class Meeting(Base):
    __tablename__ = "meetings"

    id = Column(Integer, primary_key=True, index=True)
    title = Column(String, default="Untitled Meeting")
    
    # We will save the AWS S3 link here after the video uploads
    video_url = Column(String, nullable=True) 
    
    # Text data generated by the AI
    summary = Column(Text, nullable=True)
    
    # Action items will be saved strictly as JSON so our frontend can read it easily
    action_items = Column(JSON, nullable=True)
    
    # --- ADDED: The full timestamped transcription from Groq Whisper ---
    transcript = Column(Text, nullable=True)
    
    # --- THE AI VECTOR COLUMN ---
    # Google's text-embedding-004 model outputs exactly 768 dimensions (numbers)
    embedding = Column(Vector(768), nullable=True) 
    
    created_at = Column(DateTime, default=datetime.utcnow)

    chunks = relationship("MeetingChunk", back_populates="meeting", cascade="all, delete-orphan")


class MeetingChunk(Base):
    __tablename__ = "meeting_chunks"

    id = Column(Integer, primary_key=True, index=True)
    meeting_id = Column(Integer, ForeignKey("meetings.id", ondelete="CASCADE"), nullable=False)
    chunk_index = Column(Integer, nullable=False)
    content = Column(Text, nullable=False)
    # BAAI/bge-small-en-v1.5 outputs 384-dimensional vectors
    embedding = Column(Vector(384), nullable=False)

    meeting = relationship("Meeting", back_populates="chunks")


class ChatSession(Base):
    __tablename__ = "chat_sessions"

    id = Column(Integer, primary_key=True, index=True)
    title = Column(String, default="New Conversation")
    meeting_id = Column(Integer, ForeignKey("meetings.id", ondelete="SET NULL"), nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow)

    messages = relationship("ChatMessage", back_populates="session", cascade="all, delete-orphan")


class ChatMessage(Base):
    __tablename__ = "chat_messages"

    id = Column(Integer, primary_key=True, index=True)
    session_id = Column(Integer, ForeignKey("chat_sessions.id", ondelete="CASCADE"), nullable=False)
    role = Column(String, nullable=False)  # "user" or "assistant"
    content = Column(Text, nullable=False)
    created_at = Column(DateTime, default=datetime.utcnow)

    session = relationship("ChatSession", back_populates="messages")